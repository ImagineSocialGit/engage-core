#!/usr/bin/env python3
"""Local-only, checked workflow for private Engage Core packages.

This tool owns package scaffolding and managed client Composer registration.
It intentionally delegates local symlinks to the existing dev-link/unlink tools.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[3]
PACKAGE_PREFIX = "imagine-social/"
DEFAULT_OWNER = "ImagineSocialGit"
GENERATED_HEADER = "// Generated by scripts/package.sh from config/client_package_registry.json.\n"
REGISTRY_NAME = "client_package_registry.json"
PERMISSIONS_HELPER = Path(__file__).with_name("client_file_permissions.py")
NAME_PATTERN = re.compile(r"^engage-[a-z0-9]+(?:-[a-z0-9]+)*$")
CLIENT_PATTERN = re.compile(r"^[a-z0-9][a-z0-9_-]*$")
MODULE_PATTERN = re.compile(r"^[a-z][a-z0-9_]*$")
CLASS_PATTERN = re.compile(r"^ImagineSocial\\(?:[A-Za-z][A-Za-z0-9]*\\)*[A-Za-z][A-Za-z0-9]*$")
ENV_PATTERN = re.compile(r"^[A-Z][A-Z0-9_]*$")


class WorkflowError(Exception):
    pass


def fail(message: str) -> None:
    raise WorkflowError(message)


def run(args: list[str], *, cwd: Path | None = None, capture: bool = False) -> str:
    try:
        result = subprocess.run(
            args, cwd=cwd, check=True, text=True,
            stdout=subprocess.PIPE if capture else None,
            stderr=subprocess.PIPE if capture else None,
        )
        return result.stdout.strip() if capture else ""
    except FileNotFoundError as exc:
        fail(f"Required executable not available: {args[0]}")
    except subprocess.CalledProcessError as exc:
        detail = (exc.stderr or "").strip() if capture else ""
        fail(f"Command failed ({exc.returncode}): {' '.join(args)}" + (f"\n{detail}" if detail else ""))
    return ""


def require_command(name: str) -> None:
    if shutil.which(name) is None:
        fail(f"Required executable not available: {name}")


def read_json(path: Path) -> dict:
    try:
        document = json.loads(path.read_text())
    except (ValueError, OSError) as exc:
        fail(f"Cannot read valid JSON: {path}: {exc}")
    if not isinstance(document, dict):
        fail(f"Expected a JSON object: {path}")
    return document


def pretty_json(document: dict) -> str:
    return json.dumps(document, indent=4, ensure_ascii=False) + "\n"


def php_literal(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def words(slug: str) -> list[str]:
    return slug.split("-")


def class_words(slug: str) -> str:
    return "".join(part.capitalize() for part in words(slug))


def make_descriptor(slug: str, kind: str, owner: str, platform: str = "core") -> dict:
    if not NAME_PATTERN.fullmatch(slug):
        fail("Package repository name must be engage- followed by lowercase hyphenated words.")
    integration_prefixes = {
        "core": "engage-integration-",
        "seo": "engage-seo-integration-",
        "artist": "engage-artist-integration-",
    }
    if platform not in integration_prefixes:
        fail("Package platform must be core, seo or artist.")
    if kind == "integration" and not slug.startswith(integration_prefixes[platform]):
        fail(f"{platform} integrations must be named {integration_prefixes[platform]}<provider>.")
    if kind != "integration" and any(slug.startswith(prefix) for prefix in integration_prefixes.values()):
        fail("Integration package names must be declared as type integration.")
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9-]*", owner):
        fail("Invalid GitHub owner name.")
    if platform not in ("core", "seo", "artist"):
        fail("Package platform must be core, seo or artist.")
    if platform == "seo" and not slug.startswith("engage-seo-"):
        fail("SEO package names must start with engage-seo-.")
    if platform == "artist" and not slug.startswith("engage-artist-"):
        fail("Artist package names must start with engage-artist-.")
    namespace = "ImagineSocial\\" + class_words(slug)
    identifier = slug.removeprefix(integration_prefixes[platform]) if kind == "integration" else slug.removeprefix("engage-")
    basename = class_words(identifier)
    descriptor = {
        "schema": 1,
        "name": PACKAGE_PREFIX + slug,
        "kind": kind,
        "platform": platform,
        "namespace": namespace,
        "github_owner": owner,
        "environment": {},
    }
    if kind == "integration":
        descriptor["service_provider"] = namespace + "\\" + basename + "ServiceProvider"
    elif kind == "vertical" and platform == "core":
        module_key = identifier.replace("-", "_")
        descriptor["module_key"] = module_key
        descriptor["module_class"] = namespace + "\\" + basename + "Package"
        # A freshly scaffolded vertical has no schema yet. An explicit opt-in
        # is required once the package contributes real migration files.
        descriptor["migration_scope"] = False
    elif kind == "vertical":
        shortname = slug.removeprefix("engage-seo-").removeprefix("engage-artist-")
        basename = ("Seo" if platform == "seo" else "Artist") + class_words(shortname)
        descriptor["vertical_key"] = shortname.replace("-", "_")
        descriptor["service_provider"] = namespace + "\\" + basename + "ServiceProvider"
    return descriptor


def php_file(namespace: str, classname: str, body: str, imports: str = "") -> str:
    return f"<?php\n\nnamespace {namespace};\n\n{imports}{body}\n"


def package_contents(descriptor: dict, description: str) -> dict[str, str]:
    name = descriptor["name"]
    slug = name.split("/", 1)[1]
    namespace = descriptor["namespace"]
    kind = descriptor["kind"]
    composer = {
        "$schema": "https://getcomposer.org/schema.json",
        "name": name,
        "description": description,
        "type": "library",
        "license": "proprietary",
        "require": {"php": "^8.3"},
        "autoload": {"psr-4": {namespace + "\\": "src/"}},
        "autoload-dev": {"psr-4": {namespace + "\\Tests\\": "tests/"}},
        "config": {"sort-packages": True},
    }
    platform = descriptor.get("platform", "core")
    files: dict[str, str] = {
        "composer.json": pretty_json(composer),
        "engage-package.json": pretty_json(descriptor),
        ".gitignore": "/vendor/\n/.phpunit.cache/\n/.phpunit.result.cache\n/.idea/\n.env\n.env.*\n!.env.example\n",
        "README.md": (
            f"# {slug}\n\n{description}\n\n"
            f"Composer package: `{name}`. Type: `{kind}`.\n\n"
            "The package is separate from platform and client repositories.\n"
            "Do not install a second Laravel runtime as a package dependency.\n\n"
            f"## Host platform: {platform}\n\n"
            + ("For Core, use `scripts/package.sh install CLIENT_KEY /var/www/" + slug
               + " --link` from the Core checkout.\n\n" if platform == "core" else
               "Use the existing selected-client Composer/package provider workflow on the host platform; "
               "the Core-only `package.sh install` operation is not valid for this package.\n\n")
            + "## Run tests (generic host; no selected client)\n\n"
            + "```bash\n"
            + f"cd /var/www/engage-core && ./scripts/test-package.sh {slug} --platform {platform}\n"
            + "```\n\n"
            "The selected client owns its Composer dependencies and package registration.\n"
            "The package owns its published code, metadata, and version history.\n"
            "Commit changes to each repository separately.\n\n"
            "`engage-package.json` declares package identity and registration metadata.\n"
            "Declare client environment key ownership there before installing or synchronizing it.\n"
            "Never store secret values in the descriptor.\n"
        ),
    }
    if kind == "integration":
        provider_class = descriptor["service_provider"].rsplit("\\", 1)[1]
        files[f"src/{provider_class}.php"] = php_file(
            namespace, provider_class,
            f"final class {provider_class} extends ServiceProvider\n"
            "{\n    public function register(): void\n    {\n"
            "        // Bind provider-neutral host contracts here when implemented.\n"
            "    }\n}\n",
            "use Illuminate\\Support\\ServiceProvider;\n\n",
        )
    elif kind == "vertical" and platform == "core":
        module_class = descriptor["module_class"].rsplit("\\", 1)[1]
        module_provider = module_class.removesuffix("Package") + "ModuleServiceProvider"
        module_key = descriptor["module_key"]
        files[f"src/{module_class}.php"] = php_file(
            namespace, module_class,
            f"final class {module_class}\n"
            "{\n"
            f"    public const MODULE_KEY = {php_literal(module_key)};\n\n"
            "    /** @return array<string, mixed> */\n"
            "    public static function moduleDefinition(): array\n    {\n"
            "        return [\n"
            f"            'name' => {php_literal(class_words(module_key.replace('_', '-')).replace('Services', ' Services'))},\n"
            "            'depends_on' => ['core'],\n"
            f"            'providers' => [{module_provider}::class],\n"
            "        ];\n    }\n}\n",
            f"use {namespace}\\Providers\\{module_provider};\n\n",
        )
        files[f"src/Providers/{module_provider}.php"] = php_file(
            namespace + "\\Providers", module_provider,
            f"final class {module_provider} extends ServiceProvider\n"
            "{\n    public function register(): void\n    {\n"
            "        // Register this module's public contributions here.\n"
            "    }\n}\n",
            "use Illuminate\\Support\\ServiceProvider;\n\n",
        )
        files["database/migrations/.gitkeep"] = ""
    elif kind == "vertical":
        provider_class = descriptor["service_provider"].rsplit("\\", 1)[1]
        key = descriptor["vertical_key"]
        if platform == "seo":
            files[f"src/{provider_class}.php"] = php_file(
                namespace, provider_class,
                f"final class {provider_class} extends ServiceProvider\n"
                "{\n    public function register(): void\n    {\n"
                "        // Register metadata only. Site features and routes remain opt-in.\n"
                "        $vertical = [\n"
                f"            'name' => {php_literal(class_words(key.replace('_', '-')))},\n"
                "            'default_features' => [],\n"
                "        ];\n"
                f"        $existing = config('verticals.available.{key}');\n"
                "        if ($existing !== null && $existing !== $vertical) {\n"
                f"            throw new LogicException({php_literal('Conflicting SEO vertical registration: ' + key)});\n"
                "        }\n"
                f"        config()->set('verticals.available.{key}', $vertical);\n"
                "    }\n}\n",
                "use Illuminate\\Support\\ServiceProvider;\nuse LogicException;\n\n",
            )
        else:
            files[f"src/{provider_class}.php"] = php_file(
                namespace, provider_class,
                f"final class {provider_class} extends ServiceProvider\n"
                "{\n    public function register(): void\n    {\n"
                "        // Register optional Artist Site capabilities when implemented.\n"
                "    }\n}\n",
                "use Illuminate\\Support\\ServiceProvider;\n\n",
            )
    else:
        files["src/.gitkeep"] = ""

    test_namespace = namespace + "\\Tests\\Unit"
    if kind == "vertical" and platform == "core":
        cls = descriptor["module_class"]
        key = descriptor["module_key"]
        test = php_file(
            test_namespace, "PackageScaffoldTest",
            "final class PackageScaffoldTest extends TestCase\n"
            "{\n    public function test_module_definition_is_available_but_not_enabled_by_a_scaffold(): void\n    {\n"
            f"        self::assertSame({php_literal(key)}, \\{cls}::MODULE_KEY);\n"
            f"        self::assertContains('core', \\{cls}::moduleDefinition()['depends_on']);\n"
            "    }\n}\n",
            "use PHPUnit\\Framework\\TestCase;\n\n",
        )
    elif "service_provider" in descriptor:
        cls = descriptor["service_provider"]
        test = php_file(
            test_namespace, "PackageScaffoldTest",
            "final class PackageScaffoldTest extends TestCase\n"
            "{\n    public function test_provider_class_is_loadable(): void\n    {\n"
            f"        self::assertTrue(class_exists(\\{cls}::class));\n"
            "    }\n}\n",
            "use PHPUnit\\Framework\\TestCase;\n\n",
        )
    else:
        test = php_file(
            test_namespace, "PackageScaffoldTest",
            "final class PackageScaffoldTest extends TestCase\n"
            "{\n    public function test_composer_package_metadata_matches_checkout(): void\n    {\n"
            "        $composer = json_decode(file_get_contents(dirname(__DIR__, 2).'/composer.json'), true, 512, JSON_THROW_ON_ERROR);\n"
            f"        self::assertSame({php_literal(name)}, $composer['name']);\n"
            "    }\n}\n",
            "use PHPUnit\\Framework\\TestCase;\n\n",
        )
    files["tests/Unit/PackageScaffoldTest.php"] = test
    return files


def ensure_core() -> None:
    if not (ROOT / "artisan").is_file() or not (ROOT / "bootstrap/app.php").is_file():
        fail(f"Not an Engage Core checkout: {ROOT}")


def create(args: argparse.Namespace) -> None:
    ensure_core()
    descriptor = make_descriptor(args.name, args.type, args.owner, args.platform)
    parent = Path(args.parent).expanduser().resolve() if args.parent else ROOT.parent
    target = parent / args.name
    remote = f"{args.owner}/{args.name}"
    if target.exists() or target.is_symlink():
        fail(f"Local package checkout already exists: {target}")
    print("Private package creation plan")
    print(f"  Package:    {descriptor['name']}")
    print(f"  Kind:       {args.type}")
    print(f"  Platform:   {args.platform}")
    print(f"  Local:      {target}")
    print(f"  GitHub:     {remote} (private)")
    print(f"  Namespace:  {descriptor['namespace']}")
    if args.type == "vertical" and args.platform == "core":
        print(f"  Module:     {descriptor['module_key']} (not enabled automatically)")
    elif args.type == "vertical":
        print(f"  Provider:   {descriptor['service_provider']} (opt-in client registration)")
    if args.dry_run:
        print("Dry run: no files or remote created.")
        return
    for name in ("git", "gh", "php"):
        require_command(name)
    if not parent.is_dir():
        fail(f"Package parent does not exist or is not a directory: {parent}")
    parent_is_writable = os.access(parent, os.W_OK | os.X_OK)
    if not parent_is_writable and parent != ROOT.parent:
        fail("Custom package parent is not writable; choose a writable --parent directory. "
             "Privileged creation is restricted to Core's default sibling directory.")
    run(["gh", "auth", "status", "--hostname", "github.com"], capture=True)
    if subprocess.run(["gh", "repo", "view", remote, "--json", "nameWithOwner"],
                      stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL).returncode == 0:
        fail(f"Remote repository already exists: {remote}")
    author_name = run(["git", "-C", str(ROOT), "config", "user.name"], capture=True)
    author_email = run(["git", "-C", str(ROOT), "config", "user.email"], capture=True)
    if not author_name or not author_email:
        fail("Git user.name/user.email must be configured in the Core checkout.")
    # /var/www is typically root-owned. Escalate only to create the exact,
    # initially private target directory and hand ownership to this user.
    # Git, GitHub and all package source operations remain unprivileged.
    staging_at_target = not parent_is_writable
    if staging_at_target:
        require_command("sudo")
        run(["sudo", "mkdir", "-m", "0700", "--", str(target)])
        try:
            run(["sudo", "chown", "--", f"{os.getuid()}:{os.getgid()}", str(target)])
        except WorkflowError:
            # Only the directory just created by this invocation may be removed.
            run(["sudo", "rmdir", "--", str(target)])
            raise
        if not target.is_dir() or target.is_symlink() or target.stat().st_uid != os.getuid():
            fail(f"New package directory is not owned by the current user: {target}")
        work = target
    else:
        # Preserve the atomic temporary-to-target publish behavior when the
        # parent is already writable by the developer.
        work = Path(tempfile.mkdtemp(prefix=f".{args.name}.creating.", dir=parent))
    remote_created = False
    try:
        for rel, contents in package_contents(descriptor, args.description).items():
            destination = work / rel
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(contents)
            destination.chmod(0o644)
        for directory in sorted((p for p in work.rglob("*") if p.is_dir()), key=lambda p: len(p.parts)):
            directory.chmod(0o755)
        work.chmod(0o755)
        for php in work.rglob("*.php"):
            run(["php", "-l", str(php)], capture=True)
        run(["git", "init", "-q", str(work)])
        run(["git", "-C", str(work), "config", "user.name", author_name])
        run(["git", "-C", str(work), "config", "user.email", author_email])
        run(["git", "-C", str(work), "add", "."])
        run(["git", "-C", str(work), "commit", "-q", "-m", "feat: initialize package"])
        run(["git", "-C", str(work), "branch", "-M", "main"])
        run(["gh", "repo", "create", remote, "--private"])
        remote_created = True
        run(["git", "-C", str(work), "remote", "add", "origin", f"git@github.com:{remote}.git"])
        run(["git", "-C", str(work), "push", "-u", "origin", "main"])
        if not staging_at_target:
            work.rename(target)
    except (WorkflowError, OSError):
        if remote_created:
            if not staging_at_target and not target.exists():
                work.rename(target)
            print(f"Remote was created; local package preserved at {target} for repair.", file=sys.stderr)
            print(f"Retry the push: git -C {target} push -u origin main", file=sys.stderr)
        else:
            shutil.rmtree(work, ignore_errors=True)
        raise
    print(f"Created private package: {target}")
    if args.platform == "core":
        print(f"Next: ./scripts/package.sh install CLIENT_KEY {target} --link")
    else:
        print(f"Next: register {descriptor['name']} using the {args.platform} client Composer and provider conventions.")
    print(f"Tests: ./scripts/test-package.sh {args.name} --platform {args.platform}")


def validated_descriptor(source: Path) -> dict:
    descriptor_path = source / "engage-package.json"
    if not descriptor_path.is_file():
        fail(f"Package descriptor is missing: {descriptor_path}; do not guess registry classes for existing packages.")
    descriptor = read_json(descriptor_path)
    kind = descriptor.get("kind")
    name = descriptor.get("name")
    if descriptor.get("schema") != 1 or kind not in ("integration", "vertical", "library"):
        fail("Unsupported package descriptor schema/kind.")
    if not isinstance(name, str) or not name.startswith(PACKAGE_PREFIX):
        fail("Package descriptor name must use imagine-social/<slug>.")
    slug = name.split("/", 1)[1]
    if not NAME_PATTERN.fullmatch(slug) or slug != source.name:
        fail(f"Package directory basename must match Composer package slug: {slug}")
    composer = read_json(source / "composer.json")
    if composer.get("name") != name:
        fail("Composer package name and engage-package.json name disagree.")
    namespace = descriptor.get("namespace")
    if not isinstance(namespace, str) or not CLASS_PATTERN.fullmatch(namespace + "\\Fixture"):
        fail("Invalid package namespace in descriptor.")
    expected_psr = namespace + "\\"
    if composer.get("autoload", {}).get("psr-4", {}).get(expected_psr) != "src/":
        fail("Composer PSR-4 namespace does not match the package descriptor.")
    for field in ("service_provider", "module_class"):
        value = descriptor.get(field)
        if value is not None and (not isinstance(value, str) or not CLASS_PATTERN.fullmatch(value)
                                  or not value.startswith(expected_psr)):
            fail(f"Invalid {field} class in package descriptor.")
    if kind == "integration" and not descriptor.get("service_provider"):
        fail("Integration packages must declare a service_provider.")
    platform = descriptor.get("platform", "core")
    if platform not in ("core", "seo", "artist"):
        fail("Unsupported package platform.")
    if kind == "vertical" and platform == "core" and (
            not MODULE_PATTERN.fullmatch(str(descriptor.get("module_key", "")))
            or not descriptor.get("module_class")):
        fail("Core vertical package must declare module_key and module_class.")
    if kind == "vertical" and platform != "core" and (
            descriptor.get("module_class") or not descriptor.get("service_provider")
            or not MODULE_PATTERN.fullmatch(str(descriptor.get("vertical_key", "")))):
        fail("Site vertical must declare vertical_key and a service provider, not a Core module.")
    if kind != "vertical" and ("module_key" in descriptor or "module_class" in descriptor
                               or "vertical_key" in descriptor):
        fail("Non-vertical packages cannot declare module contributions.")
    if "migration_scope" in descriptor:
        if kind != "vertical" or not isinstance(descriptor["migration_scope"], bool):
            fail("migration_scope must be a boolean owned by a vertical package.")
        if descriptor["migration_scope"]:
            migration_dir = source / "database" / "migrations"
            migration_files = list(migration_dir.glob("*.php")) if migration_dir.is_dir() else []
            if not migration_files:
                fail("Vertical package declares a migration scope without migration files. "
                     "Add real migrations before opting in; never create a placeholder migration.")
    if kind == "library" and "service_provider" in descriptor:
        # A library can explicitly opt into a shared service provider later.
        pass
    if not isinstance(descriptor.get("github_owner"), str) or not re.fullmatch(
            r"[A-Za-z0-9][A-Za-z0-9-]*", descriptor["github_owner"]):
        fail("Invalid github_owner in package descriptor.")
    env = descriptor.get("environment", {})
    if not isinstance(env, dict):
        fail("Package environment metadata must be an object.")
    for key, metadata in env.items():
        if not ENV_PATTERN.fullmatch(key) or not isinstance(metadata, dict):
            fail(f"Invalid package environment key: {key}")
        if not isinstance(metadata.get("owner"), str) or not re.fullmatch(r"[a-z][a-z0-9_]*", metadata["owner"]):
            fail(f"Environment key {key} needs a lowercase owner.")
        if not isinstance(metadata.get("secret"), bool):
            fail(f"Environment key {key} needs a boolean secret flag.")
    return descriptor


def read_client_env_value(path: Path, key: str) -> str:
    if not path.is_file():
        fail(f"Root .env is required: {path}")
    lines = [l.strip() for l in path.read_text().splitlines()
             if not l.lstrip().startswith("#") and re.match(rf"^{re.escape(key)}\s*=", l)]
    if len(lines) != 1:
        fail(f"Root .env must have exactly one active {key} assignment.")
    return lines[0].split("=", 1)[1].strip().strip("\"'")


def validate_client(client_key: str) -> Path:
    ensure_core()
    if not CLIENT_PATTERN.fullmatch(client_key):
        fail("Invalid client key.")
    client = ROOT / "client" / client_key
    config_path = client / "config" / "client.php"
    if not config_path.is_file():
        fail(f"Selected client does not exist: {client}")
    if read_client_env_value(ROOT / ".env", "APP_ENV") != "local":
        fail("Package installation is limited to APP_ENV=local.")
    if read_client_env_value(ROOT / ".env", "CLIENT_KEY") != client_key:
        fail("Client key must match the active root CLIENT_KEY. Switch clients before installation.")
    return client


def validate_registry(registry: dict) -> list[dict]:
    if registry.get("schema") != 1 or not isinstance(registry.get("packages"), list):
        fail("Unsupported managed client package registry format.")
    packages = registry["packages"]
    names: set[str] = set()
    module_keys: set[str] = set()
    env_keys: set[str] = set()
    for entry in packages:
        if not isinstance(entry, dict) or not isinstance(entry.get("name"), str):
            fail("Invalid managed client package entry.")
        name = entry["name"]
        if not name.startswith(PACKAGE_PREFIX) or not NAME_PATTERN.fullmatch(name[len(PACKAGE_PREFIX):]):
            fail(f"Invalid managed Composer package name: {name}")
        if entry.get("kind") not in ("integration", "vertical", "library"):
            fail(f"Invalid managed package kind: {name}")
        for field in ("service_provider", "module_class"):
            value = entry.get(field)
            if value is not None and (not isinstance(value, str) or not CLASS_PATTERN.fullmatch(value)):
                fail(f"Invalid managed {field} class: {name}")
        if entry["kind"] == "vertical":
            if not MODULE_PATTERN.fullmatch(str(entry.get("module_key", ""))) or not entry.get("module_class"):
                fail(f"Invalid managed vertical module: {name}")
        elif entry.get("module_key") is not None or entry.get("module_class") is not None:
            fail(f"Only vertical packages may contribute modules: {name}")
        if entry["kind"] == "integration" and not entry.get("service_provider"):
            fail(f"Integration missing service provider: {name}")
        if "migration_scope" in entry and (
                entry["kind"] != "vertical" or not isinstance(entry["migration_scope"], bool)):
            fail(f"Invalid migration_scope flag in {name}")
        if not isinstance(entry.get("environment", {}), dict):
            fail(f"Invalid managed environment metadata: {name}")
        for env_key, env_def in entry.get("environment", {}).items():
            if not ENV_PATTERN.fullmatch(env_key) or not isinstance(env_def, dict):
                fail(f"Invalid managed environment entry in {name}")
            if (not isinstance(env_def.get("owner"), str)
                    or not re.fullmatch(r"[a-z][a-z0-9_]*", env_def["owner"])
                    or not isinstance(env_def.get("secret"), bool)):
                fail(f"Invalid managed environment definition for {env_key} in {name}")
        if name in names:
            fail(f"Duplicate registered package: {name}")
        names.add(name)
        module_key = entry.get("module_key")
        if module_key is not None:
            if module_key in module_keys:
                fail(f"Two packages contribute module {module_key}.")
            module_keys.add(module_key)
        for key in entry.get("environment", {}):
            if key in env_keys:
                fail(f"Two packages claim environment key {key}.")
            env_keys.add(key)
    return packages


def manifest_php(registry: dict) -> str:
    packages = validate_registry(registry)
    providers: list[str] = []
    modules: list[str] = []
    migrations: list[str] = []
    environment: list[str] = []
    for descriptor in packages:
        provider = descriptor.get("service_provider")
        if provider:
            providers.append(f"        \\{provider}::class,")
        cls = descriptor.get("module_class")
        if cls:
            modules.append(f"        \\{cls}::MODULE_KEY => \\{cls}::moduleDefinition(),")
            # Older managed entries without this flag keep their original
            # migration registration. New empty scaffolds explicitly opt out.
            if descriptor.get("migration_scope", True):
                migrations.append(f"        \\{cls}::MODULE_KEY => \\{cls}::migrationScope(),")
        for key, metadata in descriptor.get("environment", {}).items():
            environment.append(
                f"        {php_literal(key)} => ["
                f"'owner' => {php_literal(metadata['owner'])}, "
                f"'secret' => {'true' if metadata['secret'] else 'false'}],"
            )
    groups = [("providers", providers), ("modules", modules), ("migrations", migrations), ("environment", environment)]
    lines = ["<?php", "", GENERATED_HEADER.rstrip("\n"), "", "return ["]
    for group, rows in groups:
        lines.append(f"    '{group}' => [")
        lines.extend(rows)
        lines.append("    ],")
        lines.append("")
    lines.extend(["];"])
    return "\n".join(lines) + "\n"


def safe_registry(client: Path) -> tuple[dict, bool]:
    registry_path = client / "config" / REGISTRY_NAME
    manifest_path = client / "config" / "client_packages.php"
    if not registry_path.exists():
        if manifest_path.exists():
            fail("This client has a hand-maintained config/client_packages.php. "
                 "Refusing to overwrite it. Migrate it intentionally before using managed package installation.")
        return {"schema": 1, "packages": []}, False
    registry = read_json(registry_path)
    expected = manifest_php(registry)
    if not manifest_path.is_file() or manifest_path.read_text() != expected:
        fail("Managed client_packages.php no longer matches its registry; refusing to overwrite custom edits.")
    return registry, True


def compose_client_composer(old: dict | None, descriptor: dict) -> dict:
    if old is None:
        old = {
            "$schema": "https://getcomposer.org/schema.json",
            "name": "imagine-social/client-" + descriptor.get("_client_key", "unknown"),
            "type": "project",
            "require": {"php": "^8.3"},
            "repositories": [],
            "minimum-stability": "dev",
            "prefer-stable": True,
            "config": {"sort-packages": True},
        }
    result = json.loads(json.dumps(old))
    if not isinstance(result.get("require"), dict) or not isinstance(result.get("repositories", []), list):
        fail("Unsupported existing client Composer repositories/require structure; edit deliberately.")
    if result.get("config", {}).get("vendor-dir", "vendor") != "vendor":
        fail("Selected-client vendor-dir must remain vendor.")
    name = descriptor["name"]
    slug = name.split("/", 1)[1]
    repo_url = f"git@github.com:{descriptor['github_owner']}/{slug}.git"
    for repo in result.setdefault("repositories", []):
        if repo.get("url") == repo_url:
            if repo.get("type") != "vcs":
                fail(f"VCS repository entry conflicts with existing repository: {repo_url}")
            break
    else:
        result["repositories"].append({"type": "vcs", "url": repo_url})
    existing = result["require"].get(name)
    if existing is not None and existing != "dev-main":
        fail(f"Client already requires {name} at {existing}; refusing to alter its version.")
    result["require"][name] = "dev-main"
    return result


def ensure_managed_runtime_permissions(client: Path) -> None:
    """Normalize only installer-managed paths; verify all client config as www-data."""
    run([sys.executable, str(PERMISSIONS_HELPER), "prepare-managed", str(client)], capture=True)


def verify_managed_runtime_permissions(client: Path) -> None:
    run([sys.executable, str(PERMISSIONS_HELPER), "verify-managed", str(client)], capture=True)


def verify_installed(client: Path, descriptor: dict) -> None:
    name = descriptor["name"]
    path = client / "vendor" / name
    if not path.is_dir():
        fail(f"Composer did not install expected package directory: {path}")
    run(["composer", "show", name, "--no-interaction"], cwd=client, capture=True)
    if descriptor.get("service_provider") or descriptor.get("module_class"):
        target = descriptor.get("service_provider") or descriptor.get("module_class")
        run(["php", "-r", "require $argv[1]; require $argv[2]; if (!class_exists($argv[3])) exit(3);",
             str(ROOT / "vendor" / "autoload.php"), str(client / "vendor" / "autoload.php"), target], capture=True)


def install(args: argparse.Namespace) -> None:
    client = validate_client(args.client)
    source = Path(args.source).expanduser().resolve()
    descriptor = validated_descriptor(source)
    if descriptor.get("platform", "core") != "core":
        fail("Core package.sh install handles only Core packages; use the site's client Composer/provider workflow.")
    name = descriptor["name"]
    require_command("composer") if not args.dry_run else None
    require_command("git") if not args.dry_run else None
    registry, managed = safe_registry(client)
    already = next((p for p in registry["packages"] if p["name"] == name), None)
    if already is not None and already != descriptor and not args.sync_metadata:
        fail("Package metadata changed since initial registration. "
             "Use --sync-metadata only after reviewing the new provider/module/environment contract.")
    existing_composer_path = client / "composer.json"
    old_composer = read_json(existing_composer_path) if existing_composer_path.exists() else None
    marked = {**descriptor, "_client_key": args.client}
    next_composer = compose_client_composer(old_composer, marked)
    if already is None:
        registry["packages"].append(descriptor)
    elif already != descriptor:
        registry["packages"] = [descriptor if p["name"] == name else p for p in registry["packages"]]
    next_registry = pretty_json(registry)
    next_manifest = manifest_php(registry)
    composer_update_required = (
        old_composer != next_composer or not (client / "composer.lock").is_file()
    )
    needs_update = already is None or already != descriptor or composer_update_required
    print("Selected-client package plan")
    print(f"  Client:     {args.client}")
    print(f"  Package:    {name} ({descriptor['kind']})")
    print(f"  Source:     {source}")
    print(f"  Composer:   {existing_composer_path}")
    print(f"  Manifest:   {client / 'config' / 'client_packages.php'}")
    print(f"  Operation:  {'install/update' if needs_update else 'already registered'}")
    print(f"  Local link: {'yes' if args.link else 'no'}")
    if args.dry_run:
        print("Dry run: no files, dependencies or symlinks changed.")
        return
    link_path = client / "vendor" / name
    if not needs_update:
        verify_installed(client, descriptor)
        ensure_managed_runtime_permissions(client)
        if args.link and (not link_path.is_symlink() or link_path.resolve() != source):
            run([str(ROOT / "scripts" / "dev-link-package.sh"), name, str(source), args.client])
        print("Package already installed and registered.")
        return
    if link_path.is_symlink() and (
            composer_update_required or link_path.resolve() != source):
        fail("Existing package is locally linked. Unlink before changing Composer requirements "
             "or switching the package source checkout.")
    repository = f"git@github.com:{descriptor['github_owner']}/{source.name}.git"
    remote_refs = run(["git", "ls-remote", "--heads", repository, "main"], capture=True)
    if not remote_refs:
        fail(f"Remote package main branch is unavailable: {repository}. Push the initial commit first.")
    composer_path = client / "composer.json"
    registry_path = client / "config" / REGISTRY_NAME
    manifest_path = client / "config" / "client_packages.php"
    lock_path = client / "composer.lock"
    ignore_path = client / ".gitignore"
    touched = (composer_path, registry_path, manifest_path, lock_path, ignore_path)
    backup = {path: path.read_bytes() if path.is_file() else None for path in touched}
    try:
        # The vendor tree is always generated and must never enter the client repository.
        ignore = ignore_path.read_text() if ignore_path.exists() else ""
        if "/vendor/" not in ignore.splitlines():
            ignore_path.write_text(ignore.rstrip("\n") + "\n/vendor/\n")
        composer_path.write_text(pretty_json(next_composer))
        registry_path.write_text(next_registry)
        manifest_path.write_text(next_manifest)
        run(["php", "-l", str(manifest_path)], capture=True)
        # A metadata-only manifest sync must not reinstall dependencies or
        # disturb a valid local symlink. New requirements still need Composer
        # to write a matching lockfile before validate can inspect it.
        if composer_update_required:
            command = ["composer", "update"]
            if old_composer is not None and lock_path.is_file():
                command.extend([name, "--with-all-dependencies"])
            command.extend(["--no-interaction", "--no-progress", "--no-scripts"])
            run(command, cwd=client)
        run(["composer", "validate", "--no-check-publish", "--no-interaction"], cwd=client)
        verify_installed(client, descriptor)
        # Composer may atomically replace the lockfile. Reassign the runtime
        # group before setting restrictive modes and before linking/booting.
        ensure_managed_runtime_permissions(client)
    except (WorkflowError, OSError) as exc:
        for path, content in backup.items():
            if content is None:
                path.unlink(missing_ok=True)
            else:
                path.write_bytes(content)
        try:
            ensure_managed_runtime_permissions(client)
        except WorkflowError as restore_error:
            print(f"WARNING: Restored client files still need permission repair: {restore_error}", file=sys.stderr)
        print("Client source files restored after failure; vendor artifacts may require composer install.", file=sys.stderr)
        raise exc
    if args.link and not link_path.is_symlink():
        run([str(ROOT / "scripts" / "dev-link-package.sh"), name, str(source), args.client])
    print("Package registered and installed. Commit client composer.json, composer.lock, config and .gitignore.")
    if descriptor["kind"] == "vertical":
        print(f"Module is AVAILABLE, not enabled: ./scripts/add-client-modules.sh {args.client} {descriptor['module_key']}")


def verify(args: argparse.Namespace) -> None:
    client = validate_client(args.client)
    registry, _ = safe_registry(client)
    require_command("composer")
    verify_managed_runtime_permissions(client)
    for entry in validate_registry(registry):
        verify_installed(client, entry)
        link = client / "vendor" / entry["name"]
        print(f"OK {entry['name']}" + (f" (local link -> {link.resolve()})" if link.is_symlink() else " (Composer-managed)"))
    if not registry["packages"]:
        print("No managed private packages installed.")


def main() -> int:
    parser = argparse.ArgumentParser(description="Private Engage Core package workflow")
    commands = parser.add_subparsers(dest="action", required=True)
    make = commands.add_parser("create", help="Scaffold, commit, push a new private package")
    make.add_argument("name", help="Repository basename, e.g. engage-integration-stripe")
    make.add_argument("--type", required=True, choices=("integration", "vertical", "library"))
    make.add_argument("--platform", choices=("core", "seo", "artist"), default="core")
    make.add_argument("--description", required=True)
    make.add_argument("--owner", default=os.getenv("ENGAGE_CORE_GITHUB_OWNER", DEFAULT_OWNER))
    make.add_argument("--parent", help="Parent checkout directory; defaults to Engage Core's sibling directory")
    make.add_argument("--dry-run", action="store_true")
    add = commands.add_parser("install", help="Register a scaffolded package in a selected Core client")
    add.add_argument("client")
    add.add_argument("source", help="Absolute path to package checkout")
    add.add_argument("--link", action="store_true", help="Link the package checkout for local development")
    add.add_argument("--sync-metadata", action="store_true", help="Explicitly accept changed package registration metadata")
    add.add_argument("--dry-run", action="store_true")
    check = commands.add_parser("verify", help="Check Composer and managed registration for a client")
    check.add_argument("client")
    args = parser.parse_args()
    try:
        if args.action == "create":
            create(args)
        elif args.action == "install":
            install(args)
        elif args.action == "verify":
            verify(args)
    except WorkflowError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())