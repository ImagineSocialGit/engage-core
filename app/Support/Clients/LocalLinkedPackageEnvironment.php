<?php

namespace App\Support\Clients;

use Illuminate\Support\Env;
use JsonException;
use RuntimeException;

/**
 * Development-only, in-memory package environment ownership overlay.
 *
 * Package installation/approval is still owned by the managed registry.
 * An intentionally linked, already registered sibling checkout may provide
 * its latest environment declarations without rewriting committed manifests.
 * Providers, modules, migration scopes and all other descriptor fields remain
 * pinned until an explicit reviewed --sync-metadata operation.
 */
final class LocalLinkedPackageEnvironment
{
    private const GENERATED_MARKER = '// Generated by scripts/package.sh from config/client_package_registry.json.';

    /**
     * @param array<string, mixed> $manifest
     * @return array<string, mixed>
     */
    public function apply(string $basePath, string $clientDirectory, string $manifestPath, array $manifest): array
    {
        if (Env::get('APP_ENV') !== 'local') {
            return $manifest;
        }

        $registryPath = $clientDirectory.'/config/client_package_registry.json';

        // Hand-maintained manifests and clients with no managed packages retain
        // their existing behavior. Neither gains packages implicitly.
        if (! is_file($registryPath)) {
            return $manifest;
        }

        $registry = $this->readObject($registryPath);
        $packages = $registry['packages'] ?? null;

        if (($registry['schema'] ?? null) !== 1 || ! is_array($packages) || ! array_is_list($packages)) {
            throw new RuntimeException('Local package registry schema or packages list is invalid.');
        }

        $expected = [];
        $effective = [];
        $hasLinkedPackage = false;

        foreach ($packages as $entry) {
            if (! is_array($entry) || ! is_string($entry['name'] ?? null)
                || preg_match('#^imagine-social/(engage-[a-z0-9]+(?:-[a-z0-9]+)*)$#D', $entry['name'], $match) !== 1
            ) {
                throw new RuntimeException('Local package registry contains an invalid registered package identity.');
            }

            $name = $entry['name'];
            $slug = $match[1];
            $registeredEnvironment = $this->environment($entry, $name);
            $this->mergeEnvironment($expected, $registeredEnvironment, $name);

            $source = $clientDirectory.'/vendor/imagine-social/'.$slug;

            if (! is_link($source)) {
                $this->mergeEnvironment($effective, $registeredEnvironment, $name);
                continue;
            }

            $hasLinkedPackage = true;
            $workspace = realpath(dirname(rtrim($basePath, DIRECTORY_SEPARATOR)));
            $actual = realpath($source);

            // The managed local workflow creates checkouts as siblings of Core.
            // A symlink to an arbitrary system path must not gain ENV ownership.
            if ($workspace === false || $actual === false
                || $actual !== $workspace.DIRECTORY_SEPARATOR.$slug
                || ! is_dir($actual)
            ) {
                throw new RuntimeException(
                    "Locally linked package [{$name}] is outside the trusted Core sibling checkout directory.",
                );
            }

            $composer = $this->readObject($actual.'/composer.json');

            if (($composer['name'] ?? null) !== $name) {
                throw new RuntimeException("Locally linked package [{$name}] Composer identity does not match registration.");
            }

            $descriptor = $this->readObject($actual.'/engage-package.json');
            $registeredIdentity = $entry;
            $sourceIdentity = $descriptor;
            unset($registeredIdentity['environment'], $sourceIdentity['environment']);

            if ($registeredIdentity != $sourceIdentity) {
                throw new RuntimeException(
                    "Locally linked package [{$name}] changed its provider/module or identity contract. "
                    .'Review and run package.sh install with --sync-metadata before continuing.',
                );
            }

            $this->mergeEnvironment($effective, $this->environment($descriptor, $name), $name);
        }

        if (! $hasLinkedPackage) {
            return $manifest;
        }

        $contents = file_get_contents($manifestPath);

        if (! is_string($contents) || ! str_contains($contents, self::GENERATED_MARKER)) {
            throw new RuntimeException('Local linked package mode requires an installer-generated client_packages.php.');
        }

        if (! is_array($manifest['environment'] ?? null) || $manifest['environment'] != $expected) {
            throw new RuntimeException(
                'Managed client package manifest does not match its registered environment snapshot. '
                .'Do not edit generated client_packages.php manually.',
            );
        }

        $manifest['environment'] = $effective;

        return $manifest;
    }

    /** @return array<string, mixed> */
    private function readObject(string $path): array
    {
        if (! is_file($path) || ! is_readable($path) || is_link($path)
            || ($bytes = filesize($path)) === false || $bytes > 262144
        ) {
            throw new RuntimeException("Local package descriptor [{$path}] is missing, linked or unreadable.");
        }

        try {
            $json = json_decode((string) file_get_contents($path), true, 512, JSON_THROW_ON_ERROR);
        } catch (JsonException $exception) {
            throw new RuntimeException("Local package descriptor [{$path}] contains invalid JSON.", 0, $exception);
        }

        if (! is_array($json) || array_is_list($json)) {
            throw new RuntimeException("Local package descriptor [{$path}] must be a JSON object.");
        }

        return $json;
    }

    /**
     * @param array<string, mixed> $descriptor
     * @return array<string, array{owner: string, secret: bool}>
     */
    private function environment(array $descriptor, string $name): array
    {
        $environment = $descriptor['environment'] ?? [];

        if (! is_array($environment) || ($environment !== [] && array_is_list($environment))) {
            throw new RuntimeException("Package [{$name}] environment declarations must be an object.");
        }

        $result = [];

        foreach ($environment as $key => $definition) {
            if (! is_string($key) || preg_match('/^[A-Z][A-Z0-9_]*$/D', $key) !== 1
                || ! is_array($definition)
                || count($definition) !== 2
                || ! array_key_exists('owner', $definition)
                || ! array_key_exists('secret', $definition)
                || ! is_string($definition['owner'] ?? null)
                || preg_match('/^[a-z][a-z0-9_]*$/D', $definition['owner']) !== 1
                || ! is_bool($definition['secret'] ?? null)
            ) {
                throw new RuntimeException("Package [{$name}] contains an invalid environment declaration.");
            }

            $result[$key] = [
                'owner' => $definition['owner'],
                'secret' => $definition['secret'],
            ];
        }

        return $result;
    }

    /**
     * @param array<string, array{owner: string, secret: bool}> $into
     * @param array<string, array{owner: string, secret: bool}> $from
     */
    private function mergeEnvironment(array &$into, array $from, string $package): void
    {
        foreach ($from as $key => $definition) {
            if (array_key_exists($key, $into)) {
                throw new RuntimeException(
                    "Package [{$package}] conflicts with an already registered environment key [{$key}].",
                );
            }

            $into[$key] = $definition;
        }
    }
}